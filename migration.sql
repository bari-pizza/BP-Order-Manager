    LANGUAGE plpgsql SECURITY DEFINER
    AS $$DECLARE
    order_record RECORD;
    drawer_record RECORD;
    driver_record RECORD;
BEGIN

    -- Step 1: Find the order associated with the payment
    SELECT * INTO order_record
    FROM "Order"
    WHERE order_id = COALESCE(OLD.order_id, NEW.order_id); -- Use COALESCE to handle both OLD and NEW

    -- Check if the order exists
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Order not found for payment with order_id: %', COALESCE(OLD.order_id, NEW.order_id);
    END IF;

    IF order_record.drawer_id IS NOT NULL THEN
        -- Step 2: Find the drawer associated with the order
        SELECT * INTO drawer_record
        FROM "BusinessDayDrawer"
        WHERE drawer_id = order_record.drawer_id;

        -- Check if the drawer is locked
        IF FOUND AND drawer_record.is_locked THEN
            RAISE EXCEPTION 'Cannot modify payment from order because drawer is locked';
        END IF;

    END IF;

    -- If all checks pass, allow the operation
    IF TG_OP = 'DELETE' THEN
      RETURN OLD;
    END IF;

    RETURN NEW; -- Return NEW for INSERT and UPDATE, OLD for DELETE
END;$$;


