    AS $$DECLARE
    drawer RECORD;
    order_row RECORD;
    successes JSONB := '[]'::jsonb; -- Initialize an empty JSONB array for successful order IDs
    failures JSONB := '[]'::jsonb; -- Initialize an empty JSONB array for failed orders
BEGIN
    BEGIN
        -- Fetch the drawer details based on p_drawer_id with explicit type cast to UUID
        SELECT * INTO drawer 
        FROM public."Drawer" 
        WHERE drawer_id = p_drawer_id::UUID; -- Explicitly cast p_drawer_id to UUID

        -- Ensure the drawer was found
        IF NOT FOUND THEN
            RETURN jsonb_build_object('isRPC', true, 'data', null, 'error', 'Drawer with ID ' || p_drawer_id || ' not found');
        END IF;
    EXCEPTION WHEN OTHERS THEN
        -- Handle any unexpected errors during drawer fetching
        RETURN jsonb_build_object('isRPC', true, 'data', null, 'error', SQLERRM);
    END;

    -- Loop through each order_id in the provided JSON array
    FOR order_row IN
        SELECT *
        FROM public."Order"
        WHERE order_id = ANY(
            SELECT value::UUID 
            FROM json_array_elements_text(p_order_ids) AS value
        ) -- Explicitly cast value to UUID
    LOOP
        BEGIN
            -- Validation: Check if the order's current drawer_id matches the drawer_id
            IF order_row.drawer_id = drawer.drawer_id THEN
                -- If validation passes, set drawer_id to NULL
                UPDATE public."Order"
                SET drawer_id = NULL
                WHERE order_id = order_row.order_id;

                -- Add the order_id to the successes array
                successes := successes || to_jsonb(order_row.order_id::TEXT);
            ELSE
                RAISE EXCEPTION 'Order % does not belong to the specified drawer %', order_row.order_id, p_drawer_id;
            END IF;
        EXCEPTION WHEN OTHERS THEN
            -- Add the order_id with the error message to the failures array
            failures := failures || jsonb_build_object(order_row.order_id::TEXT, SQLERRM);
        END;
    END LOOP;

    -- Return the results as a JSONB object
    RETURN jsonb_build_object(
        'isRPC', true,
        'data', jsonb_build_object('successes', successes, 'failures', failures),
        'error', null
    );
END;$$;


