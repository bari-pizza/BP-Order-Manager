    BEGIN
        -- Check if the BusinessDateSummary is locked
        SELECT is_locked INTO summary_locked
        FROM "BusinessDaySummary"
        WHERE business_date = p_business_date;

        IF summary_locked THEN
            RAISE EXCEPTION 'Cannot unlock drawer as the BusinessDateSummary is locked';
        END IF;

        -- Unlock the drawer
        UPDATE "BusinessDayDrawer"
        SET is_locked = false
        WHERE drawer_id = p_drawer_id AND business_date = p_business_date;

        -- Unlock all associated orders
        UPDATE "Order"
        SET is_locked = false
        WHERE drawer_id = p_drawer_id AND business_date = p_business_date;

        -- Unlock all payments for the associated orders
        UPDATE "Payment"
        SET is_locked = false
        WHERE order_id IN (
            SELECT order_id FROM "Order"
            WHERE drawer_id = p_drawer_id AND business_date = p_business_date
        );

        -- Add to successes
        successes := array_append(successes, p_drawer_id::TEXT);
    EXCEPTION WHEN OTHERS THEN
        -- Capture the error message
        error_message := SQLERRM;

        -- Log the error in the error_logs table
        INSERT INTO public.error_logs (error_message, context, order_id, created_at)
        VALUES (error_message, 'Unlock drawer for drawer_id: ' || p_drawer_id || ' on business_date: ' || p_business_date, NULL, now());

        -- Add to failures
        failures := failures || jsonb_build_object(p_drawer_id::TEXT, error_message);
    END;

    RETURN jsonb_build_object(
        'isRPC', true,
        'data', jsonb_build_object('successes', successes, 'failures', failures),
        'error', CASE WHEN array_length(successes, 1) IS NULL THEN error_message ELSE NULL END
